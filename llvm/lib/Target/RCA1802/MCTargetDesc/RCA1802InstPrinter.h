#ifndef LLVM_RCA1802_INST_PRINTER_H
#define LLVM_RCA1802_INST_PRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class RCA1802InstPrinter : public MCInstPrinter {
public:
  RCA1802InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &OS) override;

  // Autogenerated by TableGen
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx = 0);

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printRegN(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
};

} // end namespace llvm

#endif // LLVM_RCA1802_INST_PRINTER_H
